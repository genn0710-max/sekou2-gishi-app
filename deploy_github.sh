#!/bin/bash
# ================================================================
#  2級建築施工管理技士アプリ GitHub一発公開・同期スクリプト
# ================================================================

set -e

cd "$(dirname "$0")"

echo "================================================================"
echo "  🚀 GitHubへのコード送信（プッシュ）を開始します..."
echo "================================================================"

# 1. 未コミットの変更があれば自動コミット
if [[ -n $(git status --porcelain) ]]; then
  echo "📦 未保存の変更をコミットしています..."
  git add .
  git commit -m "update: $(date '+%Y-%m-%d %H:%M:%S') アップデート"
fi

# 2. プッシュ実行
echo "⬆️  GitHubリポジトリ（origin main）へ送信中..."
if git push -u origin main; then
  echo ""
  echo "================================================================"
  echo "  ✅ GitHubへのプッシュが正常に完了しました！"
  echo "================================================================"
  echo ""
  echo "【最後の1ステップ：Pages公開設定をONにする】"
  echo "1. 今からブラウザでGitHub Pages設定画面を自動で開きます。"
  echo "2. 「Branch」が [None] になっていたら [main] に変更して [Save] を押してください。"
  echo ""
  echo "公開URL: https://genn0710-max.github.io/sekou2-gishi-app/"
  echo "================================================================"
  
  # ブラウザでPages設定画面を開く
  sleep 2
  open "https://github.com/genn0710-max/sekou2-gishi-app/settings/pages" 2>/dev/null || true
else
  echo ""
  echo "================================================================"
  echo "  ⚠️  プッシュに失敗しました（よくある原因と対策）"
  echo "================================================================"
  echo "① GitHub上にリポジトリがまだ作られていない場合："
  echo "   https://github.com/new でリポジトリ名「sekou2-gishi-app」を作成してください。"
  echo ""
  echo "② ログイン・認証が必要な場合："
  echo "   画面の案内に従ってGitHubの認証（Personal Access Tokenなど）を行ってください。"
  echo "================================================================"
  exit 1
fi
